package nl.minjus.nfi.dt.jhashtools.utils;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

import org.junit.jupiter.api.extension.ExtendWith;

/**
 * Marks a test method that succeeds even if it throws one of the given exception types.
 */
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.RUNTIME)
@Documented
@ExtendWith(AllowedFailureExtension.class)
public @interface AllowedFailure {

    /**
     * The exception types (including subclasses) that do not fail the test.
     *
     * @return the allowed exception types
     */
    Class<? extends Throwable>[] value();
}
